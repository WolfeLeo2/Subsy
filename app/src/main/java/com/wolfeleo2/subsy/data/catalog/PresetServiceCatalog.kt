    fun findById(id: String): PresetService? = presets.firstOrNull { it.id.equals(id, ignoreCase = true) }

    fun search(query: String): List<PresetService> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return presets
        return presets.filter {
            it.name.lowercase().contains(q) ||
                it.description?.lowercase()?.contains(q) == true ||
                it.keywords.any { kw -> kw.lowercase().contains(q) }
        }
    }

    fun getByCategory(category: Category): List<PresetService> = presets.filter { it.category == category }
